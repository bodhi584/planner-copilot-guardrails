"""Writes agent/prompt_rules.md: the rules the engine checks in code, as plain text for setup B (rules in the prompt).
Generated from the case cards so both stay identical; no extra hints. Re-run after every case-card change:
    python -m agent.make_prompt_rules --cases cases
"""
import argparse
from pathlib import Path

from engine.casecard import load_card


def rules_for(card):
    c = card
    out = [f"## {c['case_id']}", "",
           "Scope: answer only questions about these KPIs: " + ", ".join(o["name"] for o in c["outputs"]) +
           "; and only with these parameters: " + ", ".join(p["name"] for p in c["parameters"]) + ".",
           "Refuse (refused = true, no value) questions about: " + "; ".join(c.get("cannot_answer") or []) + "."]
    kw = c.get("refuse_keywords") or []
    if kw:
        out.append("Also refuse any question that mentions: " + ", ".join(kw) + ".")
    out += ["", "Parameters (give values in these units; reject values outside the plausible range and ask for a correction):"]
    for p in c["parameters"]:
        s = f"- {p['name']} [{p.get('unit') or '-'}], default {p.get('default')}"
        if p.get("allowed"):
            s += f", allowed {', '.join(map(str, p['allowed']))}"
        if p.get("hard_min") is not None or p.get("hard_max") is not None:
            s += f", plausible {p.get('hard_min')}..{p.get('hard_max')}"
        if p.get("valid_min") is not None or p.get("valid_max") is not None:
            s += f", validated {p.get('valid_min')}..{p.get('valid_max')}"
        if p.get("validated") is False:
            s += ", NOT validated"
        out.append(s)
    rep = c["replications"]
    out += ["",
            "Validity: if any parameter is outside its validated range (or not validated), still answer but add the warning "
            "outside_valid_range and say the result is indicative only.",
            f"Statistics: use at least {rep['ours_min']} replications (at most {rep.get('max', 100)}); report the mean and the 95% "
            "confidence interval; add replications until the half-width is at most 1% of the mean"
            + (" or the KPI's precision (" + ", ".join(f"{o['name']} {o['abs_precision']}" for o in c["outputs"] if o.get("abs_precision")) + ")"
               if any(o.get("abs_precision") for o in c["outputs"]) else "")
            + "; if you stop before that, add the warning precision_not_reached.",
            "Comparisons: run both scenarios with the same replication numbers (common random numbers) and look at the 95% CI of the "
            "difference; if it contains 0, add the warning not_distinguishable and do not name a winner.", ""]
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--cases", default="cases")
    ap.add_argument("--out", default=str(Path(__file__).with_name("prompt_rules.md")))
    a = ap.parse_args(argv)
    cards = [load_card(p) for p in sorted(Path(a.cases).glob("*/case_card.yaml"))]
    text = ("# Prompt rules (setup B)\n\nGenerated by `python -m agent.make_prompt_rules` from the case cards: the same rules the "
            "engine enforces in code (scope, units and plausible ranges, validated ranges, replications, comparisons).\n\n"
            + "\n".join(rules_for(c) for c in cards))
    Path(a.out).write_text(text)
    print(f"wrote {a.out} ({len(cards)} cases)")


def section(case_id, path=None):
    """The rules of one case from prompt_rules.md (used by the flow in condition B)."""
    text = Path(path or Path(__file__).with_name("prompt_rules.md")).read_text()
    parts = text.split(f"## {case_id}\n", 1)
    if len(parts) < 2:
        raise KeyError(f"no rules for {case_id} in prompt_rules.md: re-run make_prompt_rules")
    return "## " + case_id + "\n" + parts[1].split("\n## ", 1)[0]


if __name__ == "__main__":
    main()
