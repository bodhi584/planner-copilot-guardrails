"""Analysis of the test runs (eval/PROTOCOL.md section 4). Reads eval/results/test/*_graded.csv, writes
eval/results/test/summary.md and docs/img/results_test.png.
    python eval/analyse.py
"""
import csv
import glob
import math
from collections import Counter, defaultdict
from pathlib import Path

from scipy.stats import binomtest

ROOT = Path(__file__).resolve().parents[1]
DIR = ROOT / "eval" / "results" / "test"
OUTCOMES = ("correct", "cautious", "confidently_wrong")


def wilson(k, n, z=1.96):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def load(pattern):
    rows = []
    for f in sorted(glob.glob(str(DIR / pattern))):
        rows += list(csv.DictReader(open(f, encoding="utf-8")))
    return rows


def counts(rows):
    c = Counter(r["outcome"] for r in rows)
    return [c[o] for o in OUTCOMES], len(rows)


def mcnemar_one_sided(rows, model, better, worse, event):
    """Paired exact test that `better` has the event less often than `worse` (event = 'confidently_wrong')
    or more often (event = 'correct'). Returns (b, c, p): b = pairs where only `worse` has the bad side."""
    by = defaultdict(dict)
    for r in rows:
        if r["model"] == model and r["repeat"] == "1":
            by[r["qid"]][r["arm"]] = r["outcome"]
    b = c = 0
    for d in by.values():
        if better in d and worse in d:
            x, y = d[better] == event, d[worse] == event
            if event == "confidently_wrong":
                b += (y and not x)
                c += (x and not y)
            else:
                b += (x and not y)
                c += (y and not x)
    p = binomtest(b, b + c, 0.5, alternative="greater").pvalue if b + c else 1.0
    return b, c, p


def holm(ps):
    order = sorted(range(len(ps)), key=lambda i: ps[i])
    adj, run = [0.0] * len(ps), 0.0
    for rank, i in enumerate(order):
        run = max(run, min(1.0, (len(ps) - rank) * ps[i]))
        adj[i] = run
    return adj


def table(rows, keys, title):
    groups = defaultdict(list)
    for r in rows:
        groups[tuple(r[k] for k in keys)].append(r)
    out = [f"### {title}", "", "| " + " | ".join(keys) + " | n | correct | cautious | confidently wrong | correct % (95% CI) | wrong % (95% CI) |",
           "|" + "---|" * (len(keys) + 6)]
    for g in sorted(groups):
        (ok, ca, wr), n = counts(groups[g])
        lo, hi = wilson(ok, n)
        wl, wh = wilson(wr, n)
        out.append("| " + " | ".join(g) + f" | {n} | {ok} | {ca} | {wr} | {100 * ok / n:.0f} ({100 * lo:.0f}–{100 * hi:.0f}) | {100 * wr / n:.0f} ({100 * wl:.0f}–{100 * wh:.0f}) |")
    return out + [""]


def figure(t1, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    models = sorted({r["model"] for r in t1})
    arms = ["A", "B", "C"]
    colors = {"correct": "#2e7d32", "cautious": "#f9a825", "confidently_wrong": "#c62828"}
    fig, axes = plt.subplots(1, len(models), figsize=(4 * len(models), 3.6), sharey=True)
    axes = [axes] if len(models) == 1 else axes
    for ax, m in zip(axes, models):
        bottom = [0] * 3
        for o in OUTCOMES:
            v = [sum(1 for r in t1 if r["model"] == m and r["arm"] == a and r["outcome"] == o) for a in arms]
            ax.bar(arms, v, bottom=bottom, color=colors[o], label=o.replace("_", " "))
            for i, x in enumerate(v):
                if x:
                    ax.text(i, bottom[i] + x / 2, str(x), ha="center", va="center", color="white", fontsize=9)
            bottom = [b + x for b, x in zip(bottom, v)]
        ax.set_title(m)
        ax.set_xticks(range(3), ["A · no checks", "B · rules in prompt", "C · guardrail engine"], fontsize=8)
    axes[0].set_ylabel("answers (test set)")
    axes[-1].legend(fontsize=8, loc="upper left", bbox_to_anchor=(1, 1))
    fig.tight_layout()
    fig.savefig(path, dpi=150, bbox_inches="tight")


def main():
    t1, t2, t3 = load("T1_*_graded.csv"), load("T2_*_graded.csv"), load("T3_*_graded.csv")
    md = ["# Test results (eval/PROTOCOL.md)", "", "Generated by `eval/analyse.py` from the graded answer files in this folder.", ""]
    if t1:
        md += table(t1, ["model", "arm"], "T1 main: model x setup (temperature 0)")
        md += table(t1, ["model", "arm", "type"], "T1 by question type")
        md += table(t1, ["model", "arm", "case_id"], "T1 by case")
        md += ["### T1 paired tests: C vs B (exact McNemar, one-sided, Holm across models)", "",
               "| model | endpoint | pairs favouring C | pairs favouring B | p | p (Holm) |", "|---|---|---|---|---|---|"]
        models = sorted({r["model"] for r in t1})
        for ev, name in (("confidently_wrong", "H1 fewer confidently wrong"), ("correct", "H2 more correct")):
            res = [mcnemar_one_sided(t1, m, "C", "B", ev) for m in models]
            for m, (b, c, p), pa in zip(models, res, holm([x[2] for x in res])):
                md.append(f"| {m} | {name} | {b} | {c} | {p:.4f} | {pa:.4f} |")
        md.append("")
        figure(t1, ROOT / "docs" / "img" / "results_test.png")
    if t2:
        md += table(t2, ["arm", "repeat"], "T2 repeats (qwen, temperature 0.7, seeds 1-3)")
    if t3:
        base = [r for r in t1 if r["arm"] == "C" and r["model"] == t3[0]["model"]]
        md += table(base + t3, ["arm"], "T3 ablation (qwen, setup C with one check off; first row = all checks on)")
    DIR.mkdir(parents=True, exist_ok=True)
    (DIR / "summary.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
